import { randomUUID } from "node:crypto";
import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { PrismaClient, type Prisma } from "@prisma/client";
import { afterAll, describe, expect, it, vi } from "vitest";
import { AiTelemetriBakimService } from "../src/ai/ayarlar/ai-telemetri-bakim.service";
import { istanbulAyBaslangici } from "../src/ai/ai-zaman";
import { AiAjanService } from "../src/ai/ajan/ai-ajan.service";
import { TenantAiService } from "../src/ai/ayarlar/tenant-ai.service";
import { istekBaglami } from "../src/core/istek-baglami";
import { finansKaynaklariCikar } from "../src/ai/ajan/finans-kaynaklari";

const envDosyasi = resolve(__dirname, "../.env");
if (existsSync(envDosyasi)) process.loadEnvFile(envDosyasi);
const db = new PrismaClient({ datasourceUrl: process.env.DATABASE_URL });
const denetim = new PrismaClient({ datasourceUrl: process.env.DATABASE_URL_MIGRATE ?? process.env.DATABASE_URL });
afterAll(async () => { await db.$disconnect(); await denetim.$disconnect(); });

describe("AI saklama tutarlılığı — gerçek PostgreSQL ve uygulama rolü", () => {
  it("tenant ayrımı, aktif işlemler, aylık bütçe, karar tarihi ve tekrar bakım tutarlıdır; test verisi rollback edilir", async () => {
    const tenantA = randomUUID(), tenantB = randomUUID();
    const simdi = new Date("2026-10-14T10:00:00Z");
    const eski = new Date("2026-01-01T00:00:00Z");
    const sinir = new Date("2026-10-07T10:00:00Z");
    const rollback = new Error("yalnız test kayıtlarını geri al");
    let dogrulandi = false;
    try {
      await db.$transaction(async (tx) => {
        const baglam = async (id: string) => { await tx.$executeRaw`SELECT set_config('app.tenant_id', ${id}, true)`; };
        async function kur(tenantId: string) {
          await baglam(tenantId);
          await tx.tenant.create({ data: { id: tenantId, unvan: "AI tutarlılık testi", vkn: tenantId } });
          const user = await tx.user.create({ data: { tenantId, eposta: `${tenantId}@test.local`, parolaHash: "test", adSoyad: "Test", rol: "yonetici" } });
          await tx.tenantAiAyari.create({ data: { tenantId, sohbetSaklamaGun: 7, telemetriSaklamaGun: 7, aylikMaliyetButcesiUsd: 100 } });
          const oturum = await tx.ajanOturumu.create({ data: { tenantId, userId: user.id, kanal: "WEB", kanalKimlik: randomUUID(), sonEtkilesim: eski } });
          await tx.ajanMesajGecmisi.create({ data: { oturumId: oturum.id, rol: "assistant", icerik: "Eski içerik", createdAt: eski } });
          return { userId: user.id, oturumId: oturum.id };
        }
        const b = await kur(tenantB);
        const a = await kur(tenantA);
        const session = (sonEtkilesim = eski) => tx.ajanOturumu.create({ data: { tenantId: tenantA, userId: a.userId, kanal: "WEB", kanalKimlik: randomUUID(), sonEtkilesim } });
        const bekleyen = await session();
        const bekleyenMesaj = await tx.ajanMesajGecmisi.create({ data: { oturumId: bekleyen.id, rol: "user", requestId: randomUUID(), icerik: "İşleniyor", createdAt: eski } });
        const yakin = await session();
        const yeniMesaj = await tx.ajanMesajGecmisi.create({ data: { oturumId: yakin.id, rol: "assistant", icerik: "Sınırdaki mesaj", createdAt: sinir } });
        const aktif = await session(simdi);
        const eskiAktifMesaj = await tx.ajanMesajGecmisi.create({ data: { oturumId: aktif.id, rol: "assistant", icerik: "Eski", createdAt: eski } });
        const islemde = await session();
        const onay = (durum: Prisma.AiOnayTalebiCreateInput["durum"], kararAt: Date | null, oturumId?: string, gecerlilikSonu = simdi) => tx.aiOnayTalebi.create({ data: { tenantId: tenantA, userId: a.userId, oturumId, kaynak: "asistan", arac: "test", parametreler: {}, ozet: "Test", durum, kararAt, gecerlilikSonu, createdAt: eski } });
        const yeniKarar = await onay("onaylandi", simdi);
        const eskiKarar = await onay("reddedildi", eski);
        const calisanOnay = await onay("isleniyor", null, islemde.id);
        const dolanOnay = await onay("bekliyor", null);
        const iz = (createdAt: Date) => tx.aiCagriIz.create({ data: { tenantId: tenantA, userId: a.userId, ozellik: "asistan", saglayici: "mock", islem: "metin", sureMs: 1, basarili: true, maliyetUsd: 5, createdAt } });
        const ayIzi = await iz(new Date("2026-10-02T00:00:00Z"));
        const aySiniriIzi = await iz(new Date("2026-09-30T21:00:00Z"));
        const ayOncesiIzi = await iz(new Date("2026-09-30T20:59:59Z"));
        const oncekiAyIzi = await iz(eski);
        const istek = (durum: string, tamamlandiAt: Date | null) => tx.aiAracIstegi.create({ data: { tenantId: tenantA, userId: a.userId, kaynak: "mcp", istekAnahtari: randomUUID(), arac: "test", girdiOzeti: "a".repeat(64), durum, tamamlandiAt, createdAt: eski } });
        const yeniTamamlanan = await istek("tamamlandi", simdi);
        const eskiTamamlanan = await istek("tamamlandi", eski);
        const calisanIstek = await istek("calisiyor", null);
        const onayIzi = await tx.aiVeriAktarimOnayi.create({ data: { tenantId: tenantA, userId: a.userId, olay: "onaylandi", saglayici: "mock", politikaSurumu: "test", createdAt: eski } });
        const prisma = { tenantIslem: async <T>(tenantId: string, fn: (t: Prisma.TransactionClient) => Promise<T>) => { await baglam(tenantId); return fn(tx); } };
        const asistan = new AiAjanService(prisma as never, {} as never);
        const yonetici = new TenantAiService(prisma as never, {} as never);
        const degerlendir = (tenantId: string, userId: string, id: string, deger: string, not = "") => istekBaglami.run({ deger: { tenantId, userId, rol: "yonetici" } }, () => asistan.geriBildirim(id, { deger, not }));
        const kaynaklar = finansKaynaklariCikar("finansal_ozet", '{"nakitVarliklar":"-12.00"}', simdi);
        const geriBildirimMesaji = await tx.ajanMesajGecmisi.create({ data: { oturumId: aktif.id, rol: "assistant", icerik: "Özel yanıt", saglayici: "mock", model: "kalite-test", createdAt: simdi, aracCagrisi: JSON.parse(JSON.stringify({ araclar: [{ ad: "cari_ara" }, { ad: "cari_ara" }], kaynaklar })) } });
        await degerlendir(tenantA, a.userId, geriBildirimMesaji.id, "yanlis", "Düzeltme notu");
        await expect(degerlendir(tenantB, b.userId, geriBildirimMesaji.id, "dogru")).rejects.toThrow(/size ait/);
        await baglam(tenantA);
        const digerKullanici = await tx.user.create({ data: { tenantId: tenantA, eposta: "diger@test.local", parolaHash: "test", adSoyad: "Diğer", rol: "satis" } });
        await expect(degerlendir(tenantA, digerKullanici.id, geriBildirimMesaji.id, "dogru")).rejects.toThrow(/size ait/);
        await expect(degerlendir(tenantA, a.userId, bekleyenMesaj.id, "dogru")).rejects.toThrow(/size ait/);
        await expect(degerlendir(tenantA, a.userId, geriBildirimMesaji.id, "yanlis", "x".repeat(501))).rejects.toThrow(/500/);
        await degerlendir(tenantA, a.userId, geriBildirimMesaji.id, "dogru", "Güncel not");
        const kalite = await yonetici.kalite(tenantA);
        expect(kalite).toMatchObject({ toplam: 1, modeller: [{ saglayici: "mock", model: "kalite-test", dogru: 1, yanlis: 0, eksik: 0 }], araclar: [{ arac: "cari_ara", dogru: 1, yanlis: 0, eksik: 0 }] });
        expect(JSON.stringify(kalite)).not.toMatch(/Özel yanıt|Güncel not/);
        const gecmis = await istekBaglami.run({ deger: { tenantId: tenantA, userId: a.userId, rol: "yonetici" } }, () => asistan.gecmis(aktif.id));
        expect(gecmis.mesajlar.find(m => m.id === geriBildirimMesaji.id)?.kaynaklar).toEqual(kaynaklar);
        const yabanciGecmis = await istekBaglami.run({ deger: { tenantId: tenantB, userId: b.userId, rol: "yonetici" } }, () => asistan.gecmis(aktif.id));
        expect(yabanciGecmis).toMatchObject({ oturumId: null, mesajlar: [] });
        await baglam(tenantA);
        const service = new AiTelemetriBakimService(prisma as never, { uret: vi.fn(), kapatEksikleri: vi.fn() } as never);
        await service.tenantBakim(tenantA, simdi);
        const oturumlar = (await tx.ajanOturumu.findMany()).map(x => x.id);
        expect(oturumlar).not.toContain(a.oturumId);
        for (const id of [bekleyen.id, yakin.id, aktif.id, islemde.id]) expect(oturumlar).toContain(id);
        expect(await tx.ajanMesajGecmisi.findUnique({ where: { id: eskiAktifMesaj.id } })).toBeNull();
        for (const id of [bekleyenMesaj.id, yeniMesaj.id]) expect(await tx.ajanMesajGecmisi.findUnique({ where: { id } })).not.toBeNull();
        expect(await tx.aiOnayTalebi.findUnique({ where: { id: eskiKarar.id } })).toBeNull();
        for (const id of [yeniKarar.id, calisanOnay.id, dolanOnay.id]) expect(await tx.aiOnayTalebi.findUnique({ where: { id } })).not.toBeNull();
        expect(await tx.aiOnayTalebi.findUnique({ where: { id: dolanOnay.id } })).toMatchObject({ durum: "suresi_doldu", kararAt: simdi });
        expect(await tx.aiCagriIz.findUnique({ where: { id: ayIzi.id } })).not.toBeNull();
        expect(await tx.aiCagriIz.findUnique({ where: { id: aySiniriIzi.id } })).not.toBeNull();
        expect(await tx.aiCagriIz.findUnique({ where: { id: ayOncesiIzi.id } })).toBeNull();
        const maliyet = await tx.aiCagriIz.aggregate({ where: { tenantId: tenantA, createdAt: { gte: istanbulAyBaslangici(simdi) } }, _sum: { maliyetUsd: true } });
        expect(maliyet._sum.maliyetUsd?.toNumber()).toBe(10);
        expect(await tx.aiCagriIz.findUnique({ where: { id: oncekiAyIzi.id } })).toBeNull();
        expect(await tx.aiAracIstegi.findUnique({ where: { id: eskiTamamlanan.id } })).toBeNull();
        for (const id of [yeniTamamlanan.id, calisanIstek.id]) expect(await tx.aiAracIstegi.findUnique({ where: { id } })).not.toBeNull();
        expect(await tx.aiVeriAktarimOnayi.findUnique({ where: { id: onayIzi.id } })).not.toBeNull();
        const tekrar = await service.tenantBakim(tenantA, simdi);
        expect(tekrar).toMatchObject({ silinen: 0, silinenIdempotency: 0, silinenSohbetMesaji: 0, silinenOturum: 0, silinenOnay: 0 });
        // Uygulama rolünün A bağlamında B'yi göremediği ve B'nin korunması.
        expect(await tx.ajanOturumu.findUnique({ where: { id: b.oturumId } })).toBeNull();
        await baglam(tenantB);
        expect(await tx.ajanOturumu.findUnique({ where: { id: b.oturumId } })).not.toBeNull();
        expect(await tx.ajanMesajGecmisi.count({ where: { oturumId: b.oturumId } })).toBe(1);
        dogrulandi = true;
        throw rollback;
      }, { timeout: 30_000 });
    } catch (hata) { if (hata !== rollback) throw hata; }
    expect(dogrulandi).toBe(true);
    expect(await denetim.tenant.count({ where: { id: { in: [tenantA, tenantB] } } })).toBe(0);
  });
});
